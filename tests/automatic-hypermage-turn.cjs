const assert = require('node:assert/strict');
const { createHypermageObservations, observeHypermageLine, nextCycleCost } = require('../public/assets/js/modules/hypermageRules.js');
const line = text => `19:36:19,694 - [Información (combate)] ${text}`;
const step = (state, text) => observeHypermageLine(state, 'Bucrota', line(text));

let state = createHypermageObservations();
state = step(state, 'Bucrota lanza el hechizo Ciclo Elemental.');
assert.equal(nextCycleCost(state), null, 'No hay inicio conocido al conectar a mitad de combate');
state = step(state, '127 segundos devueltos para el siguiente turno.');
state = step(state, 'Sotasset lanza el hechizo Vaporizar.');
state = step(state, 'Bucrota lanza el hechizo Ciclo Elemental.');
assert.equal(nextCycleCost(state), null, 'Un hechizo de otro personaje no inicia el turno del seguido');
state = step(state, '104 segundos devueltos para el siguiente turno.');
state = step(state, 'Bucrota: -2 PM');
state = step(state, 'Bucrota: Abundancia (+10 niv.) (Efecto de otro personaje)');
state = step(state, 'Bucrota: -50 PdV (agua)');
assert.equal(nextCycleCost(state), null, 'Los efectos recibidos no inician su turno');
state = step(state, 'Bucrota lanza el hechizo Mariposas Diurnas. (Crítico)');
assert.equal(nextCycleCost(state), 0);
assert.equal(state.estimatedTurn, true);
state = step(state, 'Bucrota lanza el hechizo Ciclo Elemental.');
assert.equal(nextCycleCost(state), 50);
state = step(state, '0 segundos devueltos para el siguiente turno.');
assert.equal(nextCycleCost(state), null, 'No se conserva un coste estimado tras un cambio de turno');
assert.equal(state.estimatedTurn, false);
state = step(state, 'Bucrota: 50 BC (Generación Natural)');
assert.equal(nextCycleCost(state), null, 'La generación pasiva fuera de turno no inicia su turno');
state = step(state, 'Sotasset lanza el hechizo Vaporizar.');
state = step(state, '62 segundos devueltos para el siguiente turno.');
state = step(state, 'Bucrota lanza el hechizo Ciclo Elemental.');
assert.equal(nextCycleCost(state), 50, 'El primer lanzamiento también debe contarse');
state = step(state, 'Combate terminado, haz clic aquí');
assert.equal(nextCycleCost(state), null);
assert.equal(state.turnBoundaryPending, false);
console.log('Detección estimada de turno del hipermago: correcta');
